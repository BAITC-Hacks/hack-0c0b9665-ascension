import { build, version } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pinnedVersion = '0.28.2';
const output = 'public/policy-options-worker.js';
const manifestPath = 'docs/evidence/policy-worker-build.json';
const sources = [
  'data/city.json',
  'src/browser/policy-options-worker.js',
  'src/core/policy-options.js',
  'src/core/simulator.js',
];
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(argument => argument !== '--check')) {
  throw new Error('Usage: node scripts/build-policy-worker.mjs [--check]');
}
if (version !== pinnedVersion) throw new Error(`Expected esbuild ${pinnedVersion}; run npm ci.`);

const options = {
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  charset: 'utf8', minify: false, legalComments: 'none',
  banner: { js: '// Generated by scripts/build-policy-worker.mjs; edit the shared source, then rebuild.' },
};
const result = await build({
  ...options, absWorkingDir: root, entryPoints: ['src/browser/policy-options-worker.js'],
  outfile: output, write: false, metafile: true, logLevel: 'silent',
});
const inputs = Object.keys(result.metafile.inputs).map(path => path.replaceAll('\\', '/')).sort();
if (JSON.stringify(inputs) !== JSON.stringify(sources)) {
  throw new Error(`Unexpected browser dependencies: ${inputs.join(', ')}`);
}
if (Object.values(result.metafile.outputs).some(entry => entry.imports.length > 0)) {
  throw new Error('The browser worker must be self-contained; external imports are forbidden.');
}
const normalize = text => text.replaceAll('\r\n', '\n');
const sha256 = text => createHash('sha256').update(normalize(text)).digest('hex');
const sourceHashes = Object.fromEntries(await Promise.all(sources.map(async path =>
  [path, sha256(await readFile(resolve(root, path), 'utf8'))])));
const bundle = result.outputFiles[0].text;
const manifest = JSON.stringify({
  builder: `esbuild@${version}`, options, normalization: 'UTF-8, CRLF normalized to LF',
  inputs: sourceHashes, output: { path: output, sha256: sha256(bundle) },
}, null, 2) + '\n';
if (check) {
  const [existingBundle, existingManifest] = await Promise.all([
    readFile(resolve(root, output), 'utf8'), readFile(resolve(root, manifestPath), 'utf8'),
  ]);
  if (normalize(existingBundle) !== bundle || normalize(existingManifest) !== manifest) {
    throw new Error('Browser worker is stale. Run npm run build:policy-worker and commit both generated files.');
  }
  console.log(`Browser worker matches shared source (${sha256(bundle)}).`);
} else {
  await mkdir(resolve(root, dirname(manifestPath)), { recursive: true });
  await writeFile(resolve(root, output), bundle);
  await writeFile(resolve(root, manifestPath), manifest);
  console.log(`Built ${output} (${Buffer.byteLength(bundle)} bytes) from the shared simulator.`);
}
